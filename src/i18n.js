const STORAGE_KEY = 'trident_portfolio_lang';

export class I18nManager {
  constructor() {
    const saved = localStorage.getItem(STORAGE_KEY);
    // Default to VI if saved or Vietnamese browser, otherwise EN
    this.currentLang = saved || (navigator.language && navigator.language.startsWith('vi') ? 'vi' : 'en');
    this.listeners = [];
  }

  getLang() {
    return this.currentLang;
  }

  setLang(lang) {
    if (lang !== 'vi' && lang !== 'en') return;
    this.currentLang = lang;
    localStorage.setItem(STORAGE_KEY, lang);
    this.applyToDOM();
    this.notify();
  }

  toggleLang() {
    const nextLang = this.currentLang === 'vi' ? 'en' : 'vi';
    this.setLang(nextLang);
    return nextLang;
  }

  t(key) {
    const dict = translations[this.currentLang] || translations.en;
    return dict[key] || translations.en[key] || key;
  }

  onChange(callback) {
    this.listeners.push(callback);
  }

  notify() {
    for (const cb of this.listeners) {
      try {
        cb(this.currentLang);
      } catch (err) {
        console.error('i18n listener error:', err);
      }
    }
  }

  applyToDOM() {
    document.documentElement.lang = this.currentLang;

    // Update text content with [data-i18n]
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (val !== undefined) {
        el.innerHTML = val;
      }
    });

    // Update title attributes with [data-i18n-title]
    const titleElements = document.querySelectorAll('[data-i18n-title]');
    titleElements.forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const val = this.t(key);
      if (val !== undefined) {
        el.setAttribute('title', val);
      }
    });

    // Update language toggle button text and custom vector flag badge
    const langBtnText = document.getElementById('langText');
    const langFlag = document.getElementById('langFlag');
    if (langBtnText) {
      langBtnText.textContent = this.currentLang.toUpperCase();
    }
    if (langFlag) {
      langFlag.innerHTML = FLAG_ICONS[this.currentLang] || FLAG_ICONS.vi;
    }
  }
}

